"""Generate solver_integration.c - SUNDIALS ARKODE fixed-step integrator."""
from __future__ import annotations

from cs_fmu_packager.models import MappingTable, PackageSpec


def generate_solver_impl(spec: PackageSpec, mapping: MappingTable) -> str:
    """Generate the solver_integration.c content.

    Implements SUNDIALS ARKODE-based fixed-step integration of
    the combined ODE system from all internal ME FMUs.
    """
    fmu_name = spec.metadata.get("identifier", "cs_fmu")
    total_nx = sum(
        len([v for v in fmu.variables
             if v.causality == "local" and v.variability == "continuous"])
        for fmu in mapping.fmus.values()
    )

    fmu_entries = []
    for fmu_id in mapping.execution_order:
        fmu = mapping.fmus.get(fmu_id)
        if fmu:
            nx = len([v for v in fmu.variables
                     if v.causality == "local" and v.variability == "continuous"])
            fmu_entries.append(f"    /* {fmu_id}: {fmu.model_name}, nx={nx} */")

    fmu_details = "\n".join(fmu_entries)

    return f"""/**
 * solver_integration.c - SUNDIALS ARKODE fixed-step integrator.
 *
 * Generated by cs-fmu-packager for: {fmu_name}
 * Total continuous states: {total_nx}
 * Internal FMU ODE systems:
{fmu_details}
 */

#include "fmi2_interface.h"
#include "solver_integration.h"
#include <sundials/sundials_types.h>
#include <arkode/arkode_arkstep.h>
#include <nvector/nvector_serial.h>
#include <stdio.h>
#include <stdlib.h>
#include <string.h>

/* ---------------------------------------------------------------------------
 * Combined RHS function for ARKODE.
 *
 * Computes the derivatives from all internal FMUs and concatenates them
 * into the single ARKODE state vector.
 * --------------------------------------------------------------------------- */
static int combined_rhs(realtype t, N_Vector y, N_Vector ydot, void* user_data)
{{
    WrapperInstance* wrapper = (WrapperInstance*)user_data;
    double* y_data = N_VGetArrayPointer(y);
    double* yd_data = N_VGetArrayPointer(ydot);
    int offset = 0;

    for (int i = 0; i < wrapper->num_internal_fmus; i++) {{
        InternalFMU* fmu = &wrapper->internal_fmus[i];
        if (fmu->component == NULL) continue;

        /* Set time on internal FMU */
        if (fmu->setTime) {{
            fmi2Status s = fmu->setTime(fmu->component, t);
            if (s > fmi2Warning) {{
                return -1;
            }}
        }}

        /* Set continuous states from combined vector */
        if (fmu->setContinuousStates && fmu->nx > 0) {{
            fmi2Status s = fmu->setContinuousStates(fmu->component, &y_data[offset], fmu->nx);
            if (s > fmi2Warning) {{
                return -1;
            }}
        }}

        /* Get derivatives */
        if (fmu->getDerivatives && fmu->nx > 0) {{
            fmi2Status s = fmu->getDerivatives(fmu->component, &yd_data[offset], fmu->nx);
            if (s > fmi2Warning) {{
                return -1;
            }}
        }}

        offset += fmu->nx;
    }}

    return 0;
}}

/* ---------------------------------------------------------------------------
 * Initialize the SUNDIALS solver for the wrapper.
 * --------------------------------------------------------------------------- */
int solver_init(WrapperInstance* wrapper)
{{
    /* Count total continuous states */
    int total_nx = 0;
    for (int i = 0; i < wrapper->num_internal_fmus; i++) {{
        total_nx += wrapper->internal_fmus[i].nx;
    }}

    if (total_nx == 0) {{
        return 0; /* No states to integrate */
    }}

    /* Create serial N_Vector for state */
    wrapper->nv_state = (void*)N_VNew_Serial(total_nx);
    if (wrapper->nv_state == NULL) {{
        return -1;
    }}

    /* Initialize state from internal FMUs */
    double* state_data = N_VGetArrayPointer((N_Vector)wrapper->nv_state);
    int offset = 0;
    for (int i = 0; i < wrapper->num_internal_fmus; i++) {{
        InternalFMU* fmu = &wrapper->internal_fmus[i];
        if (fmu->getContinuousStates && fmu->nx > 0) {{
            fmu->getContinuousStates(fmu->component, &state_data[offset], fmu->nx);
        }}
        offset += fmu->nx;
    }}

    /* Create ARKStep memory (explicit RK for fixed-step) */
    wrapper->arkode_mem = (void*)ARKStepCreate(NULL, combined_rhs, 0.0, (N_Vector)wrapper->nv_state);
    if (wrapper->arkode_mem == NULL) {{
        N_VDestroy((N_Vector)wrapper->nv_state);
        wrapper->nv_state = NULL;
        return -1;
    }}

    /* Set fixed step size */
    ARKStepSetFixedStep(wrapper->arkode_mem, wrapper->step_size);

    /* Attach user data */
    ARKStepSetUserData(wrapper->arkode_mem, wrapper);

    /* Allocate derivative buffer */
    wrapper->derivatives = (double*)calloc(total_nx, sizeof(double));
    if (wrapper->derivatives == NULL) {{
        return -1;
    }}

    return 0;
}}

/* ---------------------------------------------------------------------------
 * Perform one integration step over [t0, t0 + h].
 * Uses ARKODE fixed-step mode.
 * --------------------------------------------------------------------------- */
int solver_step(WrapperInstance* wrapper, double t0, double h)
{{
    if (wrapper->arkode_mem == NULL) {{
        return 0;
    }}

    realtype t_ret = t0;
    int flag = ARKStepEvolve(wrapper->arkode_mem, t0 + h, (N_Vector)wrapper->nv_state, &t_ret, ARK_NORMAL);

    if (flag < 0) {{
        return -1;
    }}

    /* Write integrated states back to internal FMUs */
    double* state_data = N_VGetArrayPointer((N_Vector)wrapper->nv_state);
    int offset = 0;
    for (int i = 0; i < wrapper->num_internal_fmus; i++) {{
        InternalFMU* fmu = &wrapper->internal_fmus[i];
        if (fmu->setContinuousStates && fmu->nx > 0) {{
            fmu->setContinuousStates(fmu->component, &state_data[offset], fmu->nx);
        }}
        offset += fmu->nx;
    }}

    wrapper->current_time = t0 + h;
    return 0;
}}

/* ---------------------------------------------------------------------------
 * Free solver resources.
 * --------------------------------------------------------------------------- */
void solver_free(WrapperInstance* wrapper)
{{
    if (wrapper->arkode_mem) {{
        ARKStepFree(&wrapper->arkode_mem);
        wrapper->arkode_mem = NULL;
    }}
    if (wrapper->nv_state) {{
        N_VDestroy((N_Vector)wrapper->nv_state);
        wrapper->nv_state = NULL;
    }}
    if (wrapper->derivatives) {{
        free(wrapper->derivatives);
        wrapper->derivatives = NULL;
    }}
}}
"""