"""Generate fixed_point_iteration.c - algebraic loop solver via fixed-point iteration."""
from __future__ import annotations

from cs_fmu_packager.models import MappingTable, PackageSpec


def generate_fixed_point_impl(spec: PackageSpec, mapping: MappingTable) -> str:
    """Generate the fixed_point_iteration.c content.

    Implements the internal-coupling evaluation used by the combined RHS:
    a single propagation pass over all internal connections plus a
    fixed-point iteration that resolves algebraic loops (strongly connected
    components) at a fixed state and time.
    """
    fmu_name = spec.metadata.get("identifier", "cs_fmu")
    num_loops = len(mapping.algebraic_loops)
    max_iter = spec.solver.algebraic_loop.max_iterations
    tolerance = spec.solver.algebraic_loop.tolerance

    return f"""/**
 * fixed_point_iteration.c - Internal coupling evaluation for algebraic loops.
 *
 * Generated by cs-fmu-packager for: {fmu_name}
 * Algebraic loops detected: {num_loops}
 * Max iterations: {max_iter}, Tolerance: {tolerance}
 *
 * These functions implement the "one equation system" semantics of the
 * wrapper.  They are called from combined_rhs() on every integrator stage
 * (and once more after the last sub-step, before wrapper outputs are read),
 * so internal connections are evaluated at the same state/time the
 * integrator is probing instead of being held from the start of the step.
 */

#include "fmi2_interface.h"
#include "fixed_point_iteration.h"
#include <stdio.h>
#include <stdlib.h>
#include <math.h>

/* ---------------------------------------------------------------------------
 * Propagate all internal connections once (source -> target).
 *
 * This is a single Jacobi sweep over the connection list at the current
 * internal-FMU state and input values.  It is used for the acyclic part of
 * the graph and for refreshing feed-through wrapper outputs after the final
 * sub-step.  Cycles are not resolved here; use wrapper_resolve_coupling().
 * --------------------------------------------------------------------------- */
void wrapper_propagate_connections(WrapperInstance* wrapper)
{{
    for (int c = 0; c < wrapper->num_connections; c++) {{
        InternalFMU* src_fmu = (InternalFMU*)wrapper->connections_src[c].fmu;
        InternalFMU* tgt_fmu = (InternalFMU*)wrapper->connections_tgt[c].fmu;
        if (src_fmu && tgt_fmu) {{
            double src_val = 0.0;
            fmi2ValueReference src_vr = wrapper->connections_src[c].vr;
            fmi2ValueReference tgt_vr = wrapper->connections_tgt[c].vr;
            src_fmu->getReal(src_fmu->component, &src_vr, 1, &src_val);
            tgt_fmu->setReal(tgt_fmu->component, &tgt_vr, 1, &src_val);
        }}
    }}
}}

/* ---------------------------------------------------------------------------
 * Perform fixed-point iteration over the internal connection graph.
 *
 * The iteration updates every target FMU input from its source FMU output
 * until the largest change between sweeps falls below the configured
 * tolerance or max_iterations is reached.  For acyclic connections this
 * converges in one or two sweeps; strongly connected components are the
 * cases that genuinely iterate.
 * --------------------------------------------------------------------------- */
int fixed_point_solve_loop(
    InternalFMU* fmus,
    int num_fmus,
    VariableMapping* connections_src,
    VariableMapping* connections_tgt,
    int num_connections,
    int max_iterations,
    double tolerance,
    double time)
{{
    int converged = 0;
    int iter = 0;

    /* Allocate workspace for previous values */
    double* prev_values = (double*)calloc(num_connections, sizeof(double));
    if (prev_values == NULL) {{
        return -1;
    }}

    /* Set time on all involved FMUs */
    for (int i = 0; i < num_fmus; i++) {{
        if (fmus[i].component && fmus[i].setTime) {{
            fmus[i].setTime(fmus[i].component, time);
        }}
    }}

    for (iter = 0; iter < max_iterations; iter++) {{
        double max_diff = 0.0;

        /* Evaluate connections: get source values, set target values */
        for (int c = 0; c < num_connections; c++) {{
            double src_value = 0.0;

            /* Get source variable value */
            InternalFMU* src_fmu = (InternalFMU*)connections_src[c].fmu;
            if (src_fmu && src_fmu->getReal) {{
                fmi2ValueReference vr = connections_src[c].vr;
                src_fmu->getReal(src_fmu->component, &vr, 1, &src_value);
            }}

            /* Set target variable value */
            InternalFMU* tgt_fmu = (InternalFMU*)connections_tgt[c].fmu;
            if (tgt_fmu && tgt_fmu->setReal) {{
                fmi2ValueReference vr = connections_tgt[c].vr;
                tgt_fmu->setReal(tgt_fmu->component, &vr, 1, &src_value);
            }}

            /* Check convergence */
            double diff = fabs(src_value - prev_values[c]);
            if (diff > max_diff) {{
                max_diff = diff;
            }}
            prev_values[c] = src_value;
        }}

        if (max_diff < tolerance) {{
            converged = 1;
            break;
        }}
    }}

    free(prev_values);

    if (!converged) {{
        return 1;
    }}

    return 0;
}}

/* ---------------------------------------------------------------------------
 * Resolve the internal coupling at the current state and time.
 *
 * Returns 0 on success (including a non-convergence warning), or -1 if the
 * iteration workspace could not be allocated.  Non-convergence is reported
 * through the FMI logger at most once per instance so that the RHS, which
 * runs on every integrator stage, cannot flood the log.
 * --------------------------------------------------------------------------- */
int wrapper_resolve_coupling(WrapperInstance* wrapper, double time)
{{
    if (wrapper->num_connections == 0) {{
        return 0;
    }}

    int result = fixed_point_solve_loop(
        wrapper->internal_fmus,
        wrapper->num_internal_fmus,
        wrapper->connections_src,
        wrapper->connections_tgt,
        wrapper->num_connections,
        wrapper->algebraic_loop_max_iterations,
        wrapper->algebraic_loop_tolerance,
        time
    );

    if (result == -1) {{
        return -1;
    }}

    if (result == 1 && !wrapper->coupling_warned) {{
        wrapper->coupling_warned = 1;
        if (wrapper->callbacks && wrapper->callbacks->logger) {{
            wrapper->callbacks->logger(
                wrapper->callbacks->componentEnvironment,
                wrapper->instance_name,
                fmi2Warning,
                "algebraicLoop",
                "Fixed-point coupling iteration did not converge after %d iterations (tolerance=%g)",
                wrapper->algebraic_loop_max_iterations,
                wrapper->algebraic_loop_tolerance
            );
        }}
    }}

    return 0;
}}
"""
