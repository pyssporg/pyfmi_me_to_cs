"""Generate fixed_point_iteration.c - algebraic loop solver via fixed-point iteration."""
from __future__ import annotations

from cs_fmu_packager.models import MappingTable, PackageSpec


def generate_fixed_point_impl(spec: PackageSpec, mapping: MappingTable) -> str:
    """Generate the fixed_point_iteration.c content.

    Implements fixed-point iteration for resolving algebraic loops
    (strongly connected components) in the internal FMU graph.
    """
    fmu_name = spec.metadata.get("identifier", "cs_fmu")
    num_loops = len(mapping.algebraic_loops)
    max_iter = spec.solver.algebraic_loop.max_iterations
    tolerance = spec.solver.algebraic_loop.tolerance

    return f"""/**
 * fixed_point_iteration.c - Fixed-point iteration for algebraic loops.
 *
 * Generated by cs-fmu-packager for: {fmu_name}
 * Algebraic loops detected: {num_loops}
 * Max iterations: {max_iter}, Tolerance: {tolerance}
 */

#include "fmi2_interface.h"
#include "fixed_point_iteration.h"
#include <stdio.h>
#include <stdlib.h>
#include <math.h>

/* ---------------------------------------------------------------------------
 * Perform fixed-point iteration for a single algebraic loop.
 *
 * For each connection within an SCC, the iteration updates the target
 * FMU variable from the source FMU variable until convergence or
 * max_iterations is reached.
 * --------------------------------------------------------------------------- */
int fixed_point_solve_loop(
    InternalFMU* fmus,
    int num_fmus,
    VariableMapping* connections_src,
    VariableMapping* connections_tgt,
    int num_connections,
    int max_iterations,
    double tolerance,
    double time)
{{
    int converged = 0;
    int iter = 0;

    /* Allocate workspace for previous values */
    double* prev_values = (double*)calloc(num_connections, sizeof(double));
    if (prev_values == NULL) {{
        return -1;
    }}

    /* Set time on all involved FMUs */
    for (int i = 0; i < num_fmus; i++) {{
        if (fmus[i].component && fmus[i].setTime) {{
            fmus[i].setTime(fmus[i].component, time);
        }}
    }}

    for (iter = 0; iter < max_iterations; iter++) {{
        double max_diff = 0.0;

        /* Evaluate connections: get source values, set target values */
        for (int c = 0; c < num_connections; c++) {{
            double src_value = 0.0;

            /* Get source variable value */
            InternalFMU* src_fmu = (InternalFMU*)connections_src[c].internal_fmu;
            if (src_fmu && src_fmu->getReal) {{
                fmi2ValueReference vr = connections_src[c].vr;
                src_fmu->getReal(src_fmu->component, &vr, 1, &src_value);
            }}

            /* Set target variable value */
            InternalFMU* tgt_fmu = (InternalFMU*)connections_tgt[c].internal_fmu;
            if (tgt_fmu && tgt_fmu->setReal) {{
                fmi2ValueReference vr = connections_tgt[c].vr;
                tgt_fmu->setReal(tgt_fmu->component, &vr, 1, &src_value);
            }}

            /* Check convergence */
            double diff = fabs(src_value - prev_values[c]);
            if (diff > max_diff) {{
                max_diff = diff;
            }}
            prev_values[c] = src_value;
        }}

        if (max_diff < tolerance) {{
            converged = 1;
            break;
        }}
    }}

    free(prev_values);

    if (!converged) {{
        return 1;
    }}

    return 0;
}}

/* ---------------------------------------------------------------------------
 * Resolve all algebraic loops in the wrapper.
 * --------------------------------------------------------------------------- */
int fixed_point_resolve_all(WrapperInstance* wrapper, double time)
{{
    if (wrapper->num_connections == 0) {{
        return 0;
    }}

    int result = fixed_point_solve_loop(
        wrapper->internal_fmus,
        wrapper->num_internal_fmus,
        wrapper->connections_src,
        wrapper->connections_tgt,
        wrapper->num_connections,
        wrapper->algebraic_loop_max_iterations,
        wrapper->algebraic_loop_tolerance,
        time
    );

    if (result == -1) {{
        return -1;
    }}

    if (result == 1) {{
        if (wrapper->callbacks && wrapper->callbacks->logger) {{
            wrapper->callbacks->logger(
                wrapper->callbacks->componentEnvironment,
                wrapper->instance_name,
                fmi2Warning,
                "algebraicLoop",
                "Fixed-point iteration did not converge after %d iterations (tolerance=%g)",
                wrapper->algebraic_loop_max_iterations,
                wrapper->algebraic_loop_tolerance
            );
        }}
    }}

    return 0;
}}
"""